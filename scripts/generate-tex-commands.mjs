// Writes the list of TeX commands the equation editor suggests, from the KaTeX version the app
// ships: every command named in KaTeX's sources that typesets with the preview's options, with the
// number of arguments it takes. Run it again after upgrading KaTeX:
//   node scripts/generate-tex-commands.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const requireFromRenderer = createRequire(join(repositoryRoot, 'packages/renderer/package.json'));
const katexRoot = dirname(requireFromRenderer.resolve('katex/package.json'));
const katex = requireFromRenderer('katex');
const katexVersion = JSON.parse(readFileSync(join(katexRoot, 'package.json'), 'utf8')).version;
const outputFile = join(repositoryRoot, 'packages/ui/src/features/equation/texCommands.ts');

/** The preview's options; the unit test checks the list against the preview itself. */
const PREVIEW_OPTIONS = {
  throwOnError: true,
  trust: false,
  strict: 'ignore',
  maxSize: 50,
  maxExpand: 1000,
  output: 'htmlAndMathml',
};
const MAX_ARGUMENTS = 3;
/**
 * Commands that need trust, which the preview never gives, and TeX programming and debugging
 * commands, which define macros or write to the console rather than typeset anything.
 */
const LEFT_OUT = new Set([
  'href',
  'url',
  'includegraphics',
  'htmlClass',
  'htmlId',
  'htmlStyle',
  'htmlData',
  'def',
  'gdef',
  'edef',
  'xdef',
  'let',
  'futurelet',
  'global',
  'long',
  'newcommand',
  'renewcommand',
  'providecommand',
  'expandafter',
  'noexpand',
  'relax',
  'message',
  'errmessage',
  'show',
  'TextOrMath',
]);
/** A command written in a source string, such as `"\\frac"`; internal ones start with `\\\\` or `@`. */
const COMMAND_IN_SOURCE = /"\\\\([A-Za-z]+)"/g;
const UNSUPPORTED_MARK = '#cc0000';
const LINE_LENGTH = 100;

function sourceTexts() {
  const functionsFolder = join(katexRoot, 'src/functions');
  const functionFiles = readdirSync(functionsFolder)
    .filter((file) => file.endsWith('.ts'))
    .map((file) => join(functionsFolder, file));
  return [...functionFiles, join(katexRoot, 'src/symbols.ts'), join(katexRoot, 'src/macros.ts')].map((file) =>
    readFileSync(file, 'utf8'),
  );
}

function commandNames() {
  const names = new Set();
  for (const text of sourceTexts()) {
    for (const match of text.matchAll(COMMAND_IN_SOURCE)) names.add(match[1]);
  }
  return [...names]
    .filter((name) => !LEFT_OUT.has(name))
    .sort((first, second) => first.localeCompare(second, 'en'));
}

function typesets(tex) {
  try {
    return !katex.renderToString(tex, PREVIEW_OPTIONS).includes(UNSUPPORTED_MARK);
  } catch {
    return false;
  }
}

/** The fewest arguments a command typesets with, or undefined if it does not typeset alone. */
function argumentCountOf(name) {
  for (let count = 0; count <= MAX_ARGUMENTS; count += 1) {
    if (typesets(`\\${name}${'{x}'.repeat(count)}`)) return count;
  }
  return undefined;
}

function wrappedNames(names) {
  const lines = [];
  let line = '';
  for (const name of names) {
    if (line !== '' && line.length + name.length + 1 > LINE_LENGTH) {
      lines.push(line);
      line = '';
    }
    line = line === '' ? name : `${line} ${name}`;
  }
  if (line !== '') lines.push(line);
  return lines.map((text, index) => `  '${index === lines.length - 1 ? text : `${text} `}'`).join(' +\n');
}

const byArgumentCount = Array.from({ length: MAX_ARGUMENTS + 1 }, () => []);
for (const name of commandNames()) {
  const count = argumentCountOf(name);
  if (count !== undefined) byArgumentCount[count].push(name);
}

const constants = byArgumentCount
  .map((names, count) => `  // ${String(count)} arguments\n${wrappedNames(names)},`)
  .join('\n');
const source = `// Generated by scripts/generate-tex-commands.mjs from KaTeX ${katexVersion}. Run it again rather than editing.

/** The commands the equation editor suggests, space-separated, by the number of arguments they take. */
export const TEX_COMMAND_NAMES_BY_ARGUMENT_COUNT: readonly string[] = [
${constants}
];
`;
const prettierOptions = await prettier.resolveConfig(outputFile);
writeFileSync(outputFile, await prettier.format(source, { ...prettierOptions, filepath: outputFile }));
console.log(
  `Wrote ${outputFile}: ${byArgumentCount.map((names, count) => `${String(names.length)} with ${String(count)}`).join(', ')} arguments.`,
);
